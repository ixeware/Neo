/** Корзина реплики v4-юнита; extra-корзины (nick, hated, shawarma, notes, sto, back) тоже. */
export type V4Bucket = 'spawn' | 'ability' | 'death' | 'kill' | 'idle' | 'nick' | 'hated' | 'shawarma' | 'notes' | 'sto' | 'back';

function pick(pool: readonly Line[] | undefined, spicy: boolean, rnd: () => number): Line | null {
  if (!pool) return null;
  const ok = spicy ? pool : pool.filter(l => !l.spicy);
  return ok.length ? ok[Math.floor(rnd() * ok.length) % ok.length] : null;
}

/** Реплика v4-юнита по типу (18..22). null — нет такого типа или корзины. Только UI. */
export function v4UnitLine(t: number, bucket: V4Bucket, spicy: boolean, rnd: () => number = Math.random): Line | null {
  const id = (Object.keys(V4_UNIT_T) as V4UnitId[]).find(k => V4_UNIT_T[k] === t);
  if (!id) return null;
  const L = V4_UNIT_LINES[id];
  const pool = bucket in L ? (L as unknown as Record<string, Line[]>)[bucket] : L.extra?.[bucket];
  return pick(pool, spicy, rnd);
}

