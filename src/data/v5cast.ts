/** Био персонажа: чистое или 18+. */
export function v5Bio(key: V5CharKey, spicy: boolean): string {
  const c = V5_CHARS[key];
  return (spicy && c.spicyBio) || c.bio;
}
/** Реплика персонажа по индексу (i — счётчик или тик). {nick} подставляет вызывающий. */
export function v5CharLine(key: V5CharKey, bucket: keyof V5Char['lines'], i: number, spicy: boolean): string {
  const pool = V5_CHARS[key].lines[bucket], n = pool.length;
  const l = pool[((Math.trunc(i) % n) + n) % n];
  return (spicy && l.spicyT) || l.t;
}
