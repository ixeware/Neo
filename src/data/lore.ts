interface Pair { clean: string[]; spicy: string[] }
const pick = (p: Pair, spicy: boolean) => {
  const pool = spicy ? [...p.clean, ...p.spicy] : p.clean;
  return pool[Math.floor(Math.random() * pool.length)];
};

