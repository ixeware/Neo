/** Карточка схода v5 по id с учётом 18+. null — такой нет. */
export function v5Card(id: number, spicy: boolean): { title: string; effect: string; minus: string; win: string } | null {
  const c = V5_CARDS.find(x => x.id === id);
  return c ? { title: (spicy && c.spicyTitle) || c.title, effect: c.effect, minus: c.minus, win: (spicy && c.win.spicyT) || c.win.t } : null;
}
