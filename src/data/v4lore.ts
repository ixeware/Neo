export function onlineLine(name: string, rnd: () => number = Math.random): Line {
  const pool = ONLINE_LINES[name] ?? ONLINE_LINES['*'];
  const l = pool[Math.floor(rnd() * pool.length) % pool.length];
  return { ...l, t: l.t.replace('{name}', name) };
}

