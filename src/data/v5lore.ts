// v5: тексты базы (постройки) и ленты — из переписки группы, по плану docs/v5 (CONTENT).
// Соседние файлы: v5cast.ts (новые персонажи), v5world.ts (сход, события, ачивки, предметы, тикер, советы).
//
// Правила:
//  - текст по умолчанию ЧИСТЫЙ; вариант 18+ лежит в полях spicy* (tools/cleanscan.ts их пропускает);
//  - в данных нет случайности: в помощники приходит индекс, уходит текст;
//  - плейсхолдеры: {k} кто сделал, {v} кого, {b} постройка (именительный), {b4} постройка (винительный),
//    {a} окончание «готов/готова/готовы», {la} окончание «упал/упала/упали», {lv} имя уровня, {p} игрок,
//    {h} герой или босс, {i} предмет, {n} число, {nick} ник. Строка, которой не хватает значения, не выбирается.

/** Строка ленты: чистый текст и, если отличается, вариант 18+. */
export interface V5Line {
  t: string;
  spicyT?: string;
  /** Только для этого ключа (постройка, предмет). */
  on?: string;
  /** Только для этой стороны (0 Атаги, 1 Курчалой). */
  side?: 0 | 1;
  /** Только при этом условии (см. комментарии у групп FEED). */
  tag?: string;
  /** Кто говорит (нет — рассказчик). */
  who?: string;
}
const L = (t: string, spicyT?: string | null, x?: Partial<V5Line>): V5Line => ({ t, ...(spicyT ? { spicyT } : null), ...x });

/** Текст строки с учётом 18+. */
export const v5text = (l: V5Line, spicy: boolean): string => (spicy && l.spicyT) || l.t;

export type V5Vars = Record<string, string | number | undefined>;
/** Подставить {k}, {v}, {b}…; null, если какого-то значения нет. */
export function v5fill(s: string, vars: V5Vars = {}): string | null {
  let ok = true;
  const out = s.replace(/\{([a-z0-9]+)\}/g, (_m, k: string) => { const x = vars[k]; if (x === undefined) { ok = false; return ''; } return String(x); });
  return ok ? out : null;
}
/** Элемент пула по индексу (любое целое, в том числе отрицательное). */
export function v5at<T>(pool: readonly T[], i: number): T | null {
  const n = pool.length;
  return n ? pool[((Math.trunc(i) % n) + n) % n] : null;
}

