// Bundles src/sim/admin.ts (+ the parts of src/sim/defs.ts it needs) into api/_lib/admcheck.js, so the
// Vercel functions validate admin commands with exactly the sim's validAdmCmd without importing src/
// at runtime (src/ uses extensionless imports that plain Node ESM cannot resolve).
//   node tools/gen-admcheck.mjs          regenerate
//   node tools/gen-admcheck.mjs --check  exit 1 when the committed file is stale
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const out = root + 'api/_lib/admcheck.js';
const r = await build({
  entryPoints: [root + 'src/sim/admin.ts'], bundle: true, format: 'esm', platform: 'neutral', target: 'es2020',
  write: false, legalComments: 'none', logLevel: 'warning',
  banner: { js: '// GENERATED by tools/gen-admcheck.mjs from src/sim/admin.ts and src/sim/defs.ts. Do not edit: run `npm run gen:api`.\n/* eslint-disable */' },
});
const code = r.outputFiles[0].text;
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
  if (cur !== code) { console.error('api/_lib/admcheck.js is stale: run `npm run gen:api`'); process.exit(1); }
  console.log('api/_lib/admcheck.js up to date (' + code.length + ' bytes)');
} else {
  writeFileSync(out, code);
  console.log('wrote api/_lib/admcheck.js (' + code.length + ' bytes)');
}
