/** Какой герой стоит за типом юнита у стороны (0 — Атаги, 1 — Курчалой). null — не герой. */
export function heroForUnit(type: number, side: 0 | 1): HeroId | null {
  switch (type) {
    case 5: return side === 0 ? 'islam' : 'zurab';
    case 6: return 'chimaev';
    case 7: return 'wou';
    case 8: return 'admin';
    case 9: return 'ersno';
    case 10: return 'bekhan';
    case 11: return 'adam';
    case 12: return 'mohmad';
    default: return null;
  }
}

/** Случайная строка с учётом 18+. Только для UI: в симуляции не вызывать. */
export function pickLine(pool: readonly Line[], spicy: boolean, rnd: () => number = Math.random): Line | null {
  const ok = spicy ? pool : pool.filter(l => !l.spicy);
  return ok.length ? ok[Math.floor(rnd() * ok.length)] : null;
}

/** Реплика героя. Если у строки нет who, говорящий — сам герой (подставлен в who). */
export function heroLine(id: HeroId, bucket: LineBucket, spicy: boolean, rnd: () => number = Math.random): Line {
  const h = HEROES[id];
  const l = pickLine(h.lines[bucket], spicy, rnd) ?? h.quote;
  return { ...l, who: l.who ?? h.name };
}

