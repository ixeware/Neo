/** Что показать для карточки схода с учётом 18+. null — у карточки нет текста v3 (берите CARDS). */
export function cardLore(id: number, spicy: boolean): { title: string; desc: string; quote: Line | null } | null {
  const c = CARD_TEXT[id];
  if (!c) return null;
  const title = spicy || !c.cleanTitle ? c.title : c.cleanTitle;
  const q = c.quote && (spicy || !c.quote.spicy) ? c.quote : c.cleanQuote ?? null;
  return { title, desc: c.desc, quote: q };
}

